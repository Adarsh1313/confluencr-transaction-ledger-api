/**
 * Walks through every requirement in the assessment brief against a RUNNING
 * server and prints PASS/FAIL per check, grouped by the brief's sections.
 *
 *   npm run dev          (in one terminal)
 *   npm run verify       (in another)
 *
 * Uses fresh accounts each run, so it is safe to repeat. Set BASE_URL to point
 * at another server (default http://localhost:3020).
 */

const BASE = (process.env.BASE_URL ?? 'http://localhost:3020').replace(/\/$/, '') + '/api/v1';
const run = Date.now().toString(36);

type Res = { status: number; body: any };

async function call(method: string, path: string, body?: unknown, raw?: string): Promise<Res> {
  const res = await fetch(BASE + path, {
    method,
    headers: body !== undefined || raw !== undefined ? { 'content-type': 'application/json' } : {},
    body: raw ?? (body !== undefined ? JSON.stringify(body) : undefined),
  });
  const text = await res.text();
  let parsed: unknown = text;
  try {
    parsed = JSON.parse(text);
  } catch {}
  return { status: res.status, body: parsed };
}

let passed = 0;
const failures: string[] = [];

function check(label: string, ok: boolean, detail = '') {
  if (ok) {
    passed++;
    console.log(`  \x1b[32m✔\x1b[0m ${label}`);
  } else {
    failures.push(label);
    console.log(`  \x1b[31m✘ ${label}\x1b[0m${detail ? `  (${detail})` : ''}`);
  }
}

const section = (title: string) => console.log(`\n\x1b[1m${title}\x1b[0m`);
const isError = (r: Res, status: number, code: string) =>
  r.status === status && r.body?.error?.code === code && typeof r.body.error.message === 'string';
const got = (r: Res) => `got ${r.status} ${r.body?.error?.code ?? ''}`.trim();

let refCount = 0;
const ref = () => `verify-${run}-${++refCount}`;
const newAccount = async (name = 'Verify') => (await call('POST', '/accounts', { name })).body.id as string;
const credit = (id: string, amount: number, reference_id = ref()) =>
  call('POST', `/accounts/${id}/transactions`, { type: 'credit', amount, reference_id });
const debit = (id: string, amount: number, reference_id = ref()) =>
  call('POST', `/accounts/${id}/transactions`, { type: 'debit', amount, reference_id });
const balance = async (id: string) => (await call('GET', `/accounts/${id}/balance`)).body.balance as number;

async function main() {
  try {
    await fetch(BASE.replace('/api/v1', '') + '/health');
  } catch {
    console.error(`Cannot reach ${BASE}. Start the server first with: npm run dev`);
    process.exit(1);
  }
  console.log(`Verifying ${BASE}`);

  section('1. Create Account');
  const created = await call('POST', '/accounts', { name: 'Asha Rao' });
  check('returns 201 with id, name, balance, created_at', created.status === 201 &&
    ['id', 'name', 'balance', 'created_at'].every((k) => k in created.body), got(created));
  check('initial balance is 0', created.body.balance === 0);
  check('created_at is generated by the system', !Number.isNaN(Date.parse(created.body.created_at)));
  const second = await call('POST', '/accounts', { name: 'Ravi' });
  check('every id is unique', second.body.id !== created.body.id);
  check('name is required', isError(await call('POST', '/accounts', {}), 400, 'VALIDATION_ERROR'));
  check('client cannot set the initial balance',
    isError(await call('POST', '/accounts', { name: 'Rich', balance: 1000 }), 400, 'VALIDATION_ERROR'));

  section('2. Add Transaction');
  const a = await newAccount();
  await credit(a, 100);
  const c = await credit(a, 50);
  check('credit: 100 + 50 = 150', c.status === 201 && (await balance(a)) === 150, got(c));
  check('transaction has id, account_id, type, amount, description, reference_id, created_at',
    ['id', 'account_id', 'type', 'amount', 'description', 'reference_id', 'created_at'].every((k) => k in c.body));
  const b = await newAccount();
  await credit(b, 100);
  const d = await debit(b, 30);
  check('debit: 100 - 30 = 70', d.status === 201 && (await balance(b)) === 70, got(d));
  const poor = await newAccount();
  await credit(poor, 100);
  const tooMuch = await debit(poor, 150);
  check('debit over balance is rejected', isError(tooMuch, 422, 'INSUFFICIENT_BALANCE'), got(tooMuch));
  check('balance remains 100 after the rejection', (await balance(poor)) === 100);

  section('2. Duplicate Transactions');
  const dupAcc = await newAccount();
  const first = await credit(dupAcc, 100, 'dup-ref');
  const again = await credit(dupAcc, 100, 'dup-ref');
  check('same reference_id on same account returns 409 "already exists"',
    isError(again, 409, 'DUPLICATE_TRANSACTION'), got(again));
  check('no new transaction is created',
    (await call('GET', `/accounts/${dupAcc}/transactions`)).body.pagination.total_records === 1);
  check('balance does not change', (await balance(dupAcc)) === 100);
  check('response includes the existing transaction', again.body?.error?.details?.transaction?.id === first.body.id);
  const other = await newAccount();
  check('same reference_id works on a different account', (await credit(other, 10, 'dup-ref')).status === 201);

  section('3. Get Account Balance');
  const bal = await call('GET', `/accounts/${a}/balance`);
  check('returns account_id and balance', bal.status === 200 && bal.body.account_id === a && bal.body.balance === 150);
  check('unknown account returns an error', isError(await call('GET', '/accounts/acc_nope/balance'), 404, 'ACCOUNT_NOT_FOUND'));

  section('4. Get Transaction History');
  const h = await newAccount();
  for (const [type, amount] of [['credit', 100], ['credit', 50], ['debit', 30], ['debit', 20], ['credit', 5]] as const) {
    await call('POST', `/accounts/${h}/transactions`, { type, amount, reference_id: `${type}-${amount}` });
  }
  const all = (await call('GET', `/accounts/${h}/transactions`)).body;
  check('no type filter returns both credits and debits', all.data.length === 5);
  const credits = (await call('GET', `/accounts/${h}/transactions?type=credit`)).body;
  check('filter type=credit', credits.data.length === 3 && credits.data.every((t: any) => t.type === 'credit'));
  const debits = (await call('GET', `/accounts/${h}/transactions?type=debit`)).body;
  check('filter type=debit', debits.data.length === 2 && debits.data.every((t: any) => t.type === 'debit'));
  const page = (await call('GET', `/accounts/${h}/transactions?page=2&limit=2`)).body;
  check('pagination with page and limit', page.data.length === 2);
  check('returns current page, page size, total records, total pages',
    JSON.stringify(page.pagination) === JSON.stringify({ page: 2, limit: 2, total_records: 5, total_pages: 3 }),
    JSON.stringify(page.pagination));
  const times = all.data.map((t: any) => Date.parse(t.created_at));
  check('sorted latest first by created_at',
    times.every((t: number, i: number) => i === 0 || t <= times[i - 1]) && all.data[0].reference_id === 'credit-5');
  check('invalid pagination returns an error',
    isError(await call('GET', `/accounts/${h}/transactions?page=0`), 400, 'INVALID_PAGINATION') &&
      isError(await call('GET', `/accounts/${h}/transactions?limit=abc`), 400, 'INVALID_PAGINATION'));

  section('5. Data Integrity');
  const txnId = all.data[0].id;
  const edits = await Promise.all(
    ['PUT', 'PATCH', 'DELETE'].map((m) => call(m, `/accounts/${h}/transactions/${txnId}`, m === 'DELETE' ? undefined : { amount: 1 })),
  );
  check('transactions cannot be edited or deleted through the API', edits.every((r) => r.status === 404));
  check('the transaction is unchanged afterwards',
    (await call('GET', `/accounts/${h}/transactions`)).body.data[0].amount === all.data[0].amount);
  const cons = await newAccount();
  await credit(cons, 100);
  await credit(cons, 50);
  await debit(cons, 30);
  await debit(cons, 20);
  check('balance consistency: 0 +100 +50 -30 -20 = 100', (await balance(cons)) === 100);
  await debit(cons, 1_000);
  check('a rejected transaction does not affect the balance', (await balance(cons)) === 100);
  const race = await newAccount();
  await credit(race, 100);
  const burst = await Promise.all(Array.from({ length: 20 }, () => debit(race, 10)));
  check('atomicity under load: 20 parallel debits of 10 on 100 → exactly 10 succeed, balance 0',
    burst.filter((r) => r.status === 201).length === 10 && (await balance(race)) === 0);

  section('7. Validations');
  const v = await newAccount();
  const bad = (payload: object) => call('POST', `/accounts/${v}/transactions`, payload);
  check('account name must be provided', isError(await call('POST', '/accounts', { name: ' ' }), 400, 'VALIDATION_ERROR'));
  check('account must exist when creating a transaction',
    isError(await call('POST', '/accounts/acc_nope/transactions', { type: 'credit', amount: 1, reference_id: 'x' }), 404, 'ACCOUNT_NOT_FOUND'));
  check('type must be credit or debit', isError(await bad({ type: 'refund', amount: 1, reference_id: 'x' }), 400, 'VALIDATION_ERROR'));
  check('amount must be greater than 0',
    isError(await bad({ type: 'credit', amount: 0, reference_id: 'x' }), 400, 'VALIDATION_ERROR') &&
      isError(await bad({ type: 'credit', amount: -5, reference_id: 'x' }), 400, 'VALIDATION_ERROR'));
  check('reference_id must be provided', isError(await bad({ type: 'credit', amount: 1 }), 400, 'VALIDATION_ERROR'));
  check('debit needs sufficient balance', isError(await bad({ type: 'debit', amount: 1, reference_id: 'x' }), 422, 'INSUFFICIENT_BALANCE'));

  section('8. Error Handling');
  const malformed = await call('POST', '/accounts', undefined, '{"name": ');
  check('invalid request body (malformed JSON) returns 400', isError(malformed, 400, 'INVALID_REQUEST_BODY'), got(malformed));
  const errorShapes = [tooMuch, again, malformed, await call('GET', '/accounts/acc_nope/balance')];
  check('every error has the same { error: { code, message, details } } shape',
    errorShapes.every((r) => r.body?.error && 'code' in r.body.error && 'message' in r.body.error && 'details' in r.body.error));

  section('9. Bonus: Money Transfer');
  const A = await newAccount('A');
  const B = await newAccount('B');
  await credit(A, 100);
  await credit(B, 50);
  const t = await call('POST', '/transfers', { from_account_id: A, to_account_id: B, amount: 30, reference_id: ref() });
  check('transfer 30: A 100 → 70, B 50 → 80',
    t.status === 201 && (await balance(A)) === 70 && (await balance(B)) === 80, got(t));
  const tPoor = await call('POST', '/transfers', { from_account_id: A, to_account_id: B, amount: 500, reference_id: ref() });
  check('source must have sufficient balance', isError(tPoor, 422, 'INSUFFICIENT_BALANCE'), got(tPoor));
  check('failed transfer changes neither account (no partial transfer)', (await balance(A)) === 70 && (await balance(B)) === 80);
  check('both accounts must exist',
    isError(await call('POST', '/transfers', { from_account_id: A, to_account_id: 'acc_nope', amount: 1, reference_id: ref() }), 404, 'ACCOUNT_NOT_FOUND'));
  check('debit and credit are recorded together with one transfer_id',
    (await call('GET', `/accounts/${A}/transactions`)).body.data[0].transfer_id === t.body.id &&
      (await call('GET', `/accounts/${B}/transactions`)).body.data[0].transfer_id === t.body.id);

  console.log(`\n${passed} passed, ${failures.length} failed`);
  process.exit(failures.length ? 1 : 0);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
